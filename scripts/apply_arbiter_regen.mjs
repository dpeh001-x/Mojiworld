// The Tower Arbiter's sprite sets regenerated without slices (arbiter regen, 2026-10-15).
// ============================================================================
// Per user: "There is honestly a lot of slice and cutoff for these, could you regenerate the sprite sequence for
// arbiter". Rays, flames and the raised sword were cut off by hard straight lines - the worst a horizontal cut across his
// pillar strike, the sword point sheared flat at the top of the frame - and the walk's blade ran off the bottom of the
// canvas. The cause was in how the sets were made: ludo.ai's animator (True Size framing) crops every frame to the source
// sprite's own outline plus ~100 px, so whatever the motion reached beyond that (a raised blade, a burst of light) was cut
// flat on that box, which lands INSIDE the game canvas; padding the source with empty space changed nothing.
// The fix is ART ONLY, shipped by the LX_APPLY2 half (scripts/apply_arbiter_regen_assets.mjs): five Arbiter sets (idle,
// walk, swing, pillar, verdict; the lunge had no slice and is unchanged) are regenerated by scripts/gen_arbiter_regen.mjs from his own frames, in a working
// frame with room around him whose crop box is stretched to the whole frame, then baked back onto the same canvas at the
// same size, x and floor line (registered on each set's shipped frame 0, feet snapped to the floor row). Same names, same
// canvas sizes, same frame counts, so the hit regions and the frame index still hold. A clip detector (border, floor row,
// and straight cut lines anywhere in the frame) passed on every frame.
// CALIBRATION (per user: "after regeneration, calibrate"): measured in the game, the pillar drew his body at 0.93 of the
// idle's and the verdict at 1.10 (so before the regen too); LX_APPLY2 re-solves their s / dx / dy through
// scripts/apply_anim_patch.mjs. The pillar now draws 7.4% bigger, so its bake base below grows with it (1160 -> 1246, the
// same "~2% over the widest draw" rule) - otherwise its frames would be upscaled on screen. The verdict keeps its base.
// Game file: the version marker and that one base value.
// Guarded + atomic + idempotent. EOL-aware.
import { readFileSync, writeFileSync, renameSync, statSync } from 'node:fs';
const F = process.env.LX_GAME_FILE || 'C:/Users/dpeh0/Mojiworld/mojiworld_game.html';
let s = readFileSync(F, 'utf8');
const n0 = s.length;
if (s.includes('THE ARBITER REGENERATED')) { console.log('already applied'); process.exit(0); }
const crlf = (s.match(/\r\n/g) || []).length, lf = (s.match(/\n/g) || []).length;
const EOL = crlf > lf / 2 ? '\r\n' : '\n';
const die = (m) => { console.error('ABORT ' + m); process.exit(1); };
const J = (...L) => L.join(EOL);
const once = (a, b, what) => { const n = s.split(a).length - 1; if (n !== 1) die(what + ' matched ' + n); s = s.replace(a, () => b); };

{
  const A = 'function _lxBossBakeBaseFor(subdir, type) {';
  once(A, J(
    '// v0.30.1786 arbiter-regen - THE ARBITER REGENERATED (art only, per user: "a lot of slice and cutoff"). Five Tower Arbiter sets -',
    '// idle, walk, swing (attack/towerArbiter), pillar (column) and verdict (his lunge had no slice) - were re-animated from his own frames with',
    '// room for their effects (the animator used to crop each frame to his outline + ~100 px, slicing blades and light flat) and',
    '// baked back onto the same canvases at the same size, x and floor line; the hit regions and the frame index are unchanged.',
    '// Calibrated in the game afterwards: the pillar (0.93 of the idle\'s body) and the verdict (1.10) were re-solved to match the',
    '// idle, so the pillar\'s base below grows with its draw (x2.1176 / 1.9709). scripts/gen_arbiter_regen.mjs made the art; the',
    '// hashes, the table updates and the calibration patches live in scripts/apply_arbiter_regen_assets.mjs.',
    A), '_lxBossBakeBaseFor');
  once("'attack/towerArbitercolumn': 1160,", "'attack/towerArbitercolumn': 1246 /* v0.30.1786 arbiter-regen - recalibrated x1.0745 */,", 'pillar bake base');
}

const grew = s.length - n0;
if (grew < 500 || grew > 1500) die('size moved ' + grew);
writeFileSync(F + '.tmp', s, 'utf8');
if (statSync(F + '.tmp').size < 5000000) die('tmp small');
{
  let done = false, lastErr = null;
  for (let a = 1; a <= 8 && !done; a++) {
    try { renameSync(F + '.tmp', F); done = true; }
    catch (e) { lastErr = e; if (e.code !== 'EPERM' && e.code !== 'EBUSY') throw e; Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1500 * a); }
  }
  if (!done) die('rename kept failing: ' + lastErr.code);
}
console.log('applied: arbiter-regen (+' + grew + ' chars)');
