//
// Why this file exists: the editor saves to localStorage, which is scoped PER
// ORIGIN. A tweak made on http://localhost is invisible when the game is opened
// from file:// or raw.githack. Baking into this committed file — loaded before
// the main script in mojiworld_game.html — makes the values apply on every
// origin. A live localStorage edit still wins (an explicit 0 px / 1.0× there
// un-bakes a type), so the dev tool keeps working. Missing file = game runs fine.
